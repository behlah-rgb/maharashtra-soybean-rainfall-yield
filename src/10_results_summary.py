"""Step 10: write docs/RESULTS_SUMMARY.md from the outputs/final tables (no number typed by hand).

Usage: python src/10_results_summary.py
Reads only files under outputs/final/ and outputs/tables/validation_* (src/05b). Every number in the
summary is printed from a table and followed by its source file. Not report prose.
"""
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config as C  # noqa: E402

T = C.OUT_FINAL / "tables"


def rd(name: str, base: Path = T) -> tuple[pd.DataFrame, str]:
    path = base / name
    assert path.exists(), f"missing {path} - run src/03 and src/05b-09 first"
    return pd.read_csv(path, comment="#"), str(path.relative_to(C.ROOT))


def pc(x: float) -> str:
    return f"{100 * x:+.2f}%"


def main() -> None:
    L = [f"# Results summary (final panel)", "",
         f"Generated by src/10_results_summary.py on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC from the output "
         "tables. Every number below is read from the file named after it. Not report prose. Results are associations "
         "under the model's assumptions; fixed effects remove only time-invariant district confounders.", ""]

    # Data
    eda, f_eda = rd("eda_summary_stats.csv")
    vd_s, f_vds = rd("validation_d_summary.csv", C.OUT_TABLES)
    dq, f_dq = rd("05c_robust_z_panel.csv")
    n = int(eda.set_index("variable").loc["ln_yield", "count"])
    L += ["## Data", "",
          f"- Panel rows: {n} (13 districts x 18 years, 2000-2017) [{f_eda}]",
          f"- Effective number of independent rainfall signals (participation ratio): {vd_s.participation_ratio.iat[0]:.2f}; "
          f"components for 90% of variance: {int(vd_s.components_90pct.iat[0])}; mean cross-district rainfall correlation "
          f"{vd_s.mean_cross_district_corr.iat[0]:.3f} [{f_vds}]",
          f"- corr(R_season, T_season): pooled {vd_s.corr_pooled.iat[0]:.3f}, within district {vd_s.corr_within.iat[0]:.3f} [{f_vds}]",
          f"- dq_flag district-years (|robust z| > {C.DQ_ROBUST_Z:g}): "
          + ", ".join(f"{r.district} {r.year} (z = {r.robust_z:.2f})" for r in dq[dq.screen_flag].itertuples()) + f" [{f_dq}]", ""]

    # Verdict
    v, f_v = rd("06_models_linear_vs_quadratic.csv")
    L += ["## Linear vs quadratic (joint test of Rc^2 = Tc^2 = 0)", ""]
    for r in v.itertuples():
        ps = ", ".join(f"{m} {getattr(r, 'p_' + m):.4f}" for m in
                       ["district_CR", "wild_district", "year_CR", "twoway_CR", "driscoll_kraay", "MBB_L3", "MBB_L2", "MBB_L4"])
        L += [f"- {r.linear_model} vs {r.quadratic_model}: **{r.verdict}** -> headline {r.headline_model} (rule A11.1). "
              f"p: {ps}; classical F p {r.p_classical_F:.4f}; AIC {r.aic_linear:.1f} vs {r.aic_quadratic:.1f} [{f_v}]"]
    headline = v.set_index("linear_model").loc["M1", "headline_model"]
    sens = v.set_index("linear_model").loc["M1", "sensitivity_model"]
    L += [""]

    # Coefficients
    se, f_se = rd("06_models_se_comparison.csv")
    L += ["## Coefficients (per 100 mm and per 1 deg C; quadratic models: marginal effect at the grand mean)", "",
          "| model | term | coef | MBB L3 95% CI | p year-CR | p district-CR | p two-way | p DK | p wild |", "|---|---|---|---|---|---|---|---|---|"]
    for m in ["M1", "M2"]:
        s = se[se.model == m]
        for t in s.term.unique():
            g = s[s.term == t].set_index("method")
            wild = f"{g.loc['wild_district', 'p']:.4f}" if "wild_district" in g.index else "-"
            L.append(f"| {m} | {t} | {g.coef.iat[0]:.5g} | [{g.loc['MBB_L3', 'ci_lo']:.4g}, {g.loc['MBB_L3', 'ci_hi']:.4g}] | "
                     f"{g.loc['year_CR', 'p']:.4f} | {g.loc['district_CR', 'p']:.4f} | {g.loc['twoway_CR', 'p']:.4f} | "
                     f"{g.loc['driscoll_kraay', 'p']:.4f} | {wild} |")
    fs, f_fs = rd("06_models_fit_stats.csv")
    f2 = fs.set_index("model")
    L += [f"", f"Source: [{f_se}]. Turning points (M2): rainfall {f2.loc['M2', 'turning_point_Rc']:.0f} mm, temperature "
          f"{f2.loc['M2', 'turning_point_Tc']:.2f} deg C [{f_fs}]. Within R2: M1 {f2.loc['M1', 'within_r2']:.3f}, M2 "
          f"{f2.loc['M2', 'within_r2']:.3f} [{f_fs}]", ""]

    # Headline 100 mm
    res, f_res = rd("08_scenario_results.csv")
    st = res[res.level == "state"]

    def row(m, sc, var):
        return st[(st.model == m) & (st.scenario == sc) & (st.variant == var)].iloc[0]

    h = row(headline, "deficit_100mm", "A")
    L += ["## Headline: 100 mm deficit (mean of the 13 districts, T fixed = variant A)", "",
          f"- **{headline}: {pc(h.pct)}** [MBB L3 95%: {pc(h.pct_lo_L3)}, {pc(h.pct_hi_L3)}]; MBB L2 [{pc(h.pct_lo_L2)}, "
          f"{pc(h.pct_hi_L2)}]; MBB L4 [{pc(h.pct_lo_L4)}, {pc(h.pct_hi_L4)}]; district bootstrap [{pc(h.pct_lo_districts)}, "
          f"{pc(h.pct_hi_districts)}]. kg/ha: {h.kgha:+.1f} [{h.kgha_lo_L3:+.1f}, {h.kgha_hi_L3:+.1f}] "
          f"(baseline = district mean observed yield) [{f_res}]"]
    o = row(sens, "deficit_100mm", "A")
    L += [f"- {sens} (sensitivity): {pc(o.pct)} [{pc(o.pct_lo_L3)}, {pc(o.pct_hi_L3)}]; {o.kgha:+.1f} kg/ha [{f_res}]",
          f"- Range across {headline} and {sens}: {pc(min(h.pct, o.pct))} to {pc(max(h.pct, o.pct))} [{f_res}]"]
    for m in [headline, sens]:
        b = row(m, "deficit_100mm", "B")
        L.append(f"- Variant B (T moves with R, exploratory), {m}: {pc(b.pct)} [{pc(b.pct_lo_L3)}, {pc(b.pct_hi_L3)}] [{f_res}]")
    for sc in ["weak_monsoon_90pct", "weak_monsoon_80pct"]:
        for var in ["A", "B"]:
            w = row(headline, sc, var)
            L.append(f"- {sc} (ILLUSTRATIVE), {headline}, variant {var}: {pc(w.pct)} [{pc(w.pct_lo_L3)}, {pc(w.pct_hi_L3)}]; "
                     f"{w.kgha:+.1f} kg/ha [{f_res}]")
    for m, sc in [("M2_rain_only", "deficit_100mm"), ("timing", "deficit_100mm_split")]:
        e = row(m, sc, "A")
        L.append(f"- Exploratory {m} ({sc}): {pc(e.pct)} [{pc(e.pct_lo_L3)}, {pc(e.pct_hi_L3)}] [{f_res}]")
    sub = res[(res.level == "subdivision") & (res.model == headline) & (res.scenario == "deficit_100mm") & (res.variant == "A")]
    L.append("- By subdivision (" + headline + ", A): " + "; ".join(
        f"{r.unit} {pc(r.pct)} [{pc(r.pct_lo_L3)}, {pc(r.pct_hi_L3)}]" for r in sub.itertuples()) + f" [{f_res}]")
    dd = res[(res.level == "district") & (res.model == headline) & (res.scenario == "deficit_100mm") & (res.variant == "A")]
    L += [f"- District range ({headline}, A): {pc(dd.pct.min())} ({dd.loc[dd.pct.idxmin(), 'unit']}) to {pc(dd.pct.max())} "
          f"({dd.loc[dd.pct.idxmax(), 'unit']}) [{f_res}]", ""]

    # Held-out
    L += ["## Held-out prediction (leave one year out)", "",
          f"- RMSE ln: M1 {f2.loc['M1', 'loyo_rmse_ln']:.4f}, M2 {f2.loc['M2', 'loyo_rmse_ln']:.4f}, trend-only "
          f"{f2.loc['trend_only', 'loyo_rmse_ln']:.4f} [{f_fs}]",
          f"- RMSE kg/ha naive / Duan-smeared: M1 {f2.loc['M1', 'loyo_rmse_kgha_naive']:.1f} / {f2.loc['M1', 'loyo_rmse_kgha_smeared']:.1f}; "
          f"M2 {f2.loc['M2', 'loyo_rmse_kgha_naive']:.1f} / {f2.loc['M2', 'loyo_rmse_kgha_smeared']:.1f}; trend-only "
          f"{f2.loc['trend_only', 'loyo_rmse_kgha_naive']:.1f} / {f2.loc['trend_only', 'loyo_rmse_kgha_smeared']:.1f}; levels: "
          f"M1_level {f2.loc['M1_level', 'loyo_rmse_kgha_naive']:.1f}, M2_level {f2.loc['M2_level', 'loyo_rmse_kgha_naive']:.1f}, "
          f"trend_only_level {f2.loc['trend_only_level', 'loyo_rmse_kgha_naive']:.1f} [{f_fs}]", ""]

    # Trend
    tr, f_tr = rd("06_models_trend.csv")
    L += ["## Trend re-examined with 2016-2017 (A13.4e)", ""]
    for r in tr.itertuples():
        extra = f"; MBB L3 CI [{r.mbb_ci_lo:.4f}, {r.mbb_ci_hi:.4f}]" if pd.notna(r.mbb_ci_lo) else ""
        L.append(f"- {r.years}, {r.model}: {r.trend:+.4f} ln/yr ({r.pct_per_year:+.2f}%/yr), year-CR p {r.p_year_CR:.3f}{extra} [{f_tr}]")
    L += [""]

    # Robustness
    rb, f_rb = rd("09_robust_results.csv")
    L += ["## Robustness (100 mm, T fixed, mean over districts; 95% interval, method per row)", "",
          "| variant | M1 | M2 | interval method |", "|---|---|---|---|"]
    for vname in dict.fromkeys(rb.variant):
        cells = []
        for m in ["M1", "M2"]:
            r = rb[(rb.variant == vname) & (rb.model == m)].iloc[0]
            cells.append(f"{pc(r.pct_100mm)} [{pc(r.pct_lo)}, {pc(r.pct_hi)}]")
        L.append(f"| {vname} | {cells[0]} | {cells[1]} | {r.interval_method} |")
    for m in ["M1", "M2"]:
        r = rb[(rb.model == m) & (rb.variant != "base")]
        core = r[~r.variant.str.startswith("window") & (r.variant != "year_fe")]
        L.append(f"- {m}: range over all variants {pc(r.pct_100mm.min())} ({r.loc[r.pct_100mm.idxmin(), 'variant']}) to "
                 f"{pc(r.pct_100mm.max())} ({r.loc[r.pct_100mm.idxmax(), 'variant']}); excluding window and year-FE variants "
                 f"{pc(core.pct_100mm.min())} to {pc(core.pct_100mm.max())}")
    L += [f"Source: [{f_rb}]", ""]
    vs, f_vs = rd("09_robust_variance_share.csv")
    L += ["Variance share of district-demeaned weather explained by year dummies (A14.1): " + "; ".join(
        f"{r.variable} {r.share_explained_by_year_dummies:.3f}" for r in vs.itertuples()) + f" [{f_vs}]", ""]
    wdec, f_w = rd("09_robust_weighting_decomposition.csv")
    L += ["Area weighting (M1): " + "; ".join(f"{r.weights} {pc(r.pct_100mm)}" for r in wdec.itertuples()) + f" [{f_w}]", ""]

    # Diagnostics
    dt, f_dt = rd("07_diag_tests.csv")
    lo, f_lo = rd("07_diag_leave_one_district_out.csv")
    co, f_co = rd("07_diag_collinearity.csv")
    L += ["## Diagnostics (headline pair)", ""]
    for r in dt[dt.model == headline].itertuples():
        L.append(f"- {r.test}: stat {r.stat:.3f}" + (f", p {r.p:.4f}" if pd.notna(r.p) else "") + f" [{f_dt}]")
    for m in ["M1", "M2"]:
        g = lo[(lo.model == m) & (lo.dropped != "(none)")]
        L.append(f"- Leave-one-district-out, {m}: {pc(g.pct_100mm_at_mean_R.min())} to {pc(g.pct_100mm_at_mean_R.max())} [{f_lo}]")
    vif = co[(co.model == "M2") & co.term.isin(["Rc", "Tc", "Rc_sq", "Tc_sq", "trend"])]
    L += [f"- Max VIF (M2, within): {vif.VIF.max():.2f}; within corr(Rc, Tc) "
          f"{co[co.term == 'within corr(Rc, Tc)'].VIF.iat[0]:.3f} [{f_co}]", ""]

    # Sanity checks (A14.5)
    hc, f_hc = rd("11_sanity_headline_recompute.csv")
    sy, f_sy = rd("11_sanity_symmetry.csv")
    tp, f_tp = rd("11_sanity_turning_points.csv")
    L += ["## Sanity checks (A14.5)", "",
          f"- Independent numpy recomputation vs src/08: max |diff| {hc.abs_diff_pct.max():.1e} (pct), "
          f"{hc.abs_diff_kgha.max():.1e} (kg/ha) -> {'PASS' if hc.abs_diff_pct.max() < 1e-9 else 'FAIL'} [{f_hc}]"]
    for r in sy.itertuples():
        L.append(f"- Symmetry {r.model}: deficit {pc(r.deficit_100mm)}, surplus {pc(r.surplus_100mm)}, "
                 f"|surplus|/|deficit| {r.ratio_abs_surplus_to_abs_deficit:.3f} [{f_sy}]")
    for r in tp.itertuples():
        L.append(f"- Turning point {r.variable}: {r.turning_point:.2f} ({r.shape}); share of observations below "
                 f"{r.share_obs_below:.3f}, above {r.share_obs_above:.3f}; within-district SD {r.within_district_sd_pooled:.3f} [{f_tp}]")
    L += [""]

    # Anomalies
    cs, f_cs = rd("05c_cases.csv")
    nb, f_nb = rd("validation_b_normals_comparison.csv", C.OUT_TABLES)
    va, f_va = rd("validation_a_subdivision_comparison.csv", C.OUT_TABLES)
    L += ["## Anomalies and data-quality notes", ""]
    for r in cs.itertuples():
        L.append(f"- {r.district} {r.year} ({r.why}): gridded {r.gridded_R_season_mm:.0f} mm vs district median "
                 f"{r.district_median_mm:.0f}; max daily cell {r.max_daily_cell_mm:.0f} mm; cell-days > 300 mm {r.cell_days_gt_300}; "
                 f"sentinels {r.sentinel_minus999}; gridded/IMD subdivision ratio {r.ratio_gridded_sub_over_imd:.2f} [{f_cs}]")
    for r in nb[nb.flag_gt_25pct].itertuples():
        L.append(f"- Normals check flag: {r.district} gridded/normal = {r.ratio_grid_over_normal:.2f} (in panel: {r.in_panel}) [{f_nb}]")
    L.append("- Gridded vs IMD subdivision (2000-2015): " + "; ".join(
        f"{r.subdivision} r = {r.corr:.3f}, ratio {r.mean_ratio_grid_over_imd:.3f}" for r in va.itertuples()) + f" [{f_va}]")
    yfe = rb[rb.variant == "year_fe"].set_index("model")
    L += [f"- Year fixed effects (stability result, A14.1) shrink the effect: M1 {pc(yfe.loc['M1', 'pct_100mm'])} "
          f"[{pc(yfe.loc['M1', 'pct_lo'])}, {pc(yfe.loc['M1', 'pct_hi'])}], M2 {pc(yfe.loc['M2', 'pct_100mm'])} "
          f"[{pc(yfe.loc['M2', 'pct_lo'])}, {pc(yfe.loc['M2', 'pct_hi'])}] (MBB L3) [{f_rb}]",
          "- dq_flag (A13.4c, kept as applied, A14.2) flagged Buldhana wet years, not the Western Ghats districts; the Ghats "
          "are covered by the drop_kolhapur_sangli run.",
          "- Temperature: 1-degree IMD grid; several districts share cells; 7 old districts contain no cell centre "
          "(data/interim/grid_cell_weights.csv).",
          "- Old-district boundaries: Partur taluka (Jalna, from Parbhani) kept in Aurangabad (limitation, A11.3).", ""]
    out = C.ROOT / "docs" / "RESULTS_SUMMARY.md"
    out.write_text("\n".join(L) + "\n")
    print(f"Wrote {out.relative_to(C.ROOT)} ({len(L)} lines)")


if __name__ == "__main__":
    main()
