def rd(name):
    return pd.read_csv(T / name, comment="#")


def md(df: pd.DataFrame, fmt: dict | None = None) -> list:
    fmt = fmt or {}
    d = df.copy()
    for c, f in fmt.items():
        d[c] = d[c].map(lambda x, f=f: f.format(x) if pd.notna(x) else "")
    head = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    return [head, sep] + ["| " + " | ".join(map(str, r)) + " |" for r in d.itertuples(index=False)]


def pct(x):
    return f"{100 * x:+.2f}%"


def main() -> None:
    L = ["# Report inputs (tables and figure list only)", "",
         "Generated by src/12_report_inputs.py from data/processed/panel_final.csv and outputs/final/tables. "
         "Captions only; no interpretation.", ""]
    p = pd.read_csv(C.PANEL_FINAL_FILE)

    # 1 districts
    d = p.groupby("district").agg(subdivision=("subdivision", "first"), mean_area_kha=("area_kha", "mean"),
                                  mean_yield_kgha=("yield_kgha", "mean")).reset_index()
    d["subdivision"] = d.subdivision.map(SUBLABEL)
    L += ["## Table 1. Districts (13), 2000-2017: mean soybean area, mean yield, IMD rainfall subdivision", ""]
    L += md(d, {"mean_area_kha": "{:.1f}", "mean_yield_kgha": "{:.0f}"}) + ["", "Source: data/processed/panel_final.csv", ""]

    # 2 summary statistics
    s = rd("eda_summary_stats.csv")
    s = s[s.variable.isin(["ln_yield", "yield_kgha", "R_season", "R_early", "R_late", "T_season", "dry_spell_max",
                           "area_kha", "trend"])][["variable", "count", "mean", "std", "min", "50%", "max"]]
    L += ["## Table 2. Summary statistics of model variables (234 district-years)", ""]
    L += md(s, {c: "{:.3f}" for c in ["mean", "std", "min", "50%", "max"]} | {"count": "{:.0f}"})
    L += ["", "Source: outputs/final/tables/eda_summary_stats.csv", ""]

    # 3 coefficients
    se = rd("06_models_se_comparison.csv")
    L += ["## Table 3. Coefficients, M1 and M2 (ln yield; per 100 mm and per 1 deg C; centred at grand means)", ""]
    rows = []
    for m in ["M1", "M2"]:
        g = se[se.model == m]
        for t in g.term.unique():
            x = g[g.term == t].set_index("method")
            rows.append({"model": m, "term": t, "coef": x.coef.iat[0], "SE district-CR": x.loc["district_CR", "se"],
                         "p district-CR": x.loc["district_CR", "p"], "SE MBB L3": x.loc["MBB_L3", "se"],
                         "MBB L3 95% CI": f"[{x.loc['MBB_L3', 'ci_lo']:.4f}, {x.loc['MBB_L3', 'ci_hi']:.4f}]",
                         "p MBB L3": x.loc["MBB_L3", "p"], "p year-CR": x.loc["year_CR", "p"]})
    L += md(pd.DataFrame(rows), {"coef": "{:.5f}", "SE district-CR": "{:.5f}", "p district-CR": "{:.4f}",
                                  "SE MBB L3": "{:.5f}", "p MBB L3": "{:.4f}", "p year-CR": "{:.4f}"})
    L += ["", "Source: outputs/final/tables/06_models_se_comparison.csv", ""]

    # 4 model comparison
    v = rd("06_models_linear_vs_quadratic.csv").set_index("linear_model").loc["M1"]
    fs = rd("06_models_fit_stats.csv").set_index("model")
    L += ["## Table 4a. Linear vs quadratic: joint test of Rc^2 = Tc^2 = 0 (p-values)", ""]
    L += md(pd.DataFrame([{"method": m, "p": v[f"p_{m}"]} for m in
                          ["district_CR", "wild_district", "year_CR", "twoway_CR", "driscoll_kraay", "MBB_L3"]]), {"p": "{:.4f}"})
    L += ["", f"Verdict: {v.verdict}; headline model: {v.headline_model}. Source: outputs/final/tables/06_models_linear_vs_quadratic.csv", "",
          "## Table 4b. Fit and held-out prediction (leave one year out)", ""]
    ft = fs.loc[["M1", "M2", "trend_only"], ["within_r2", "aic", "bic", "loyo_rmse_ln", "loyo_rmse_kgha_naive",
                                              "loyo_rmse_kgha_smeared"]].reset_index()
    L += md(ft, {"within_r2": "{:.4f}", "aic": "{:.2f}", "bic": "{:.2f}", "loyo_rmse_ln": "{:.4f}",
                 "loyo_rmse_kgha_naive": "{:.1f}", "loyo_rmse_kgha_smeared": "{:.1f}"})
    L += ["", "Source: outputs/final/tables/06_models_fit_stats.csv", ""]

    # 5 diagnostics
    dt = rd("07_diag_tests.csv")[["model", "test", "stat", "p"]]
    L += ["## Table 5. Residual diagnostics", ""] + md(dt, {"stat": "{:.3f}", "p": "{:.4f}"})
    L += ["", "Source: outputs/final/tables/07_diag_tests.csv", ""]

    # 6 scenarios
    r = rd("08_scenario_results.csv")
    st = r[(r.level == "state") & r.model.isin(["M1", "M2"])].copy()
    st["pct"] = st.pct.map(pct)
    st["95% CI (MBB L3)"] = [f"[{pct(a)}, {pct(b)}]" for a, b in zip(st.pct_lo_L3, st.pct_hi_L3)]
    st["kg/ha"] = st.kgha.map(lambda x: f"{x:+.1f}")
    st["kg/ha 95% CI"] = [f"[{a:+.1f}, {b:+.1f}]" for a, b in zip(st.kgha_lo_L3, st.kgha_hi_L3)]
    L += ["## Table 6a. Scenarios, mean of the 13 districts (variant A = T fixed, headline; B = T moves with R)", ""]
    L += md(st[["model", "scenario", "variant", "role", "pct", "95% CI (MBB L3)", "kg/ha", "kg/ha 95% CI"]])
    L += ["", "kg/ha baseline = district mean observed yield over the panel years. Source: outputs/final/tables/08_scenario_results.csv", ""]
    dd = r[(r.level == "district") & r.model.isin(["M1", "M2"]) & (r.scenario == "deficit_100mm")].copy()
    dd["pct (95% CI)"] = [f"{pct(x)} [{pct(a)}, {pct(b)}]" for x, a, b in zip(dd.pct, dd.pct_lo_L3, dd.pct_hi_L3)]
    dd["kg/ha (95% CI)"] = [f"{x:+.1f} [{a:+.1f}, {b:+.1f}]" for x, a, b in zip(dd.kgha, dd.kgha_lo_L3, dd.kgha_hi_L3)]
    L += ["## Table 6b. 100 mm deficit by district (MBB L3 intervals)", ""]
    L += md(dd[["unit", "model", "variant", "Rbar_mm", "Tbar_C", "pct (95% CI)", "kg/ha (95% CI)"]].rename(columns={"unit": "district"}),
            {"Rbar_mm": "{:.0f}", "Tbar_C": "{:.2f}"})
    L += ["", "Source: outputs/final/tables/08_scenario_results.csv", ""]

    # 7 robustness
    rb = rd("09_robust_results.csv")
    rows = []
    for vn in dict.fromkeys(rb.variant):
        x = rb[rb.variant == vn].set_index("model")
        rows.append({"variant": vn, "n": int(x.loc["M1", "n"]),
                     "M1": f"{pct(x.loc['M1', 'pct_100mm'])} [{pct(x.loc['M1', 'pct_lo'])}, {pct(x.loc['M1', 'pct_hi'])}]",
                     "M2": f"{pct(x.loc['M2', 'pct_100mm'])} [{pct(x.loc['M2', 'pct_lo'])}, {pct(x.loc['M2', 'pct_hi'])}]",
                     "interval method": x.loc["M1", "interval_method"]})
    L += ["## Table 7. Robustness: 100 mm deficit, T fixed, mean over districts", ""] + md(pd.DataFrame(rows))
    vs = rd("09_robust_variance_share.csv")
    L += ["", "## Table 7b. Share of district-demeaned weather variance explained by year dummies", ""]
    L += md(vs[["variable", "share_explained_by_year_dummies"]], {"share_explained_by_year_dummies": "{:.3f}"})
    L += ["", "Source: outputs/final/tables/09_robust_results.csv, 09_robust_variance_share.csv", ""]

    # 8 figures
    listed = {f for f, _, _ in FIGURES}
    on_disk = {str(x.relative_to(C.ROOT)) for x in (C.OUT_FINAL / "figures").glob("*.png")}
    missing = sorted(f for f in listed if not (C.ROOT / f).exists())
    unlisted = sorted(on_disk - listed)
    assert not missing, f"listed figures missing on disk: {missing}"
    assert not unlisted, f"figures in outputs/final/figures not listed: {unlisted}"
    L += ["## Figure list", ""] + md(pd.DataFrame(FIGURES, columns=["file", "caption", "report subsection"]))
    out = C.ROOT / "docs" / "REPORT_INPUTS.md"
    out.write_text("\n".join(L) + "\n")
    print(f"Wrote {out.relative_to(C.ROOT)} ({len(L)} lines; {len(FIGURES)} figures)")


if __name__ == "__main__":
    main()
